// Sorted longest-first so longer prefixes win
// (e.g. `_gac_gb_` before `_gac_`).
const OCD_PREFIX_KEYS = Object.keys(OCD_PREFIX).sort((a, b) => b.length - a.length);

function classifyCookie(name) {
  if (!name) return null;
  if (OCD_EXACT[name]) return OCD_EXACT[name];
  for (let i = 0; i < OCD_PREFIX_KEYS.length; i++) {
    const p = OCD_PREFIX_KEYS[i];
    if (name.startsWith(p)) return OCD_PREFIX[p];
  }
  return null;
}

// Coarse "is this a tracker" bucket for scoring callers.
// Analytics + Marketing = trackers; everything else = essential/neutral.
function isTrackerCategory(category) {
  return category === 'Analytics' || category === 'Marketing';
}

if (typeof self !== 'undefined') {
  self.OCD_EXACT = OCD_EXACT;
  self.OCD_PREFIX = OCD_PREFIX;
  self.classifyCookie = classifyCookie;
  self.isTrackerCategory = isTrackerCategory;
}
